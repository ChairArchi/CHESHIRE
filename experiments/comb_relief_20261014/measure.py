"""One broad existing-comb mask from saved fine native-fan nonplanarity.

No aspect-ratio or world-axis orientation gate is applied. Geometry and shading
are not modified; source-bound measurements and one symmetric mask are saved.
"""
from pathlib import Path
import argparse
import hashlib
import importlib.util
import json
import shutil
import time

import numpy as np


HERE = Path(__file__).resolve().parent
FROZEN = HERE.parent/'diagonal_facet_finish_20261014/measure.py'
FROZEN_SHA = '40a19abf240bb79cfe6fe4ed328a5fba7cb663ebdf2c5fab794dd4a962b19c02'
DEFAULT_ROOT = Path('E:/CHESHIRE_DATA/experiments/comb_relief_20261014/trial01')
LOST_ROI = [475, 700, 740, 899]
RECIPE = {
    'schema': 'CHESHIRE_BROAD_EXISTING_COMB_RELIEF_MASK_V1',
    'normalized_height_support': [.08, .94], 'height_feather': .03,
    'maximum_edge_fade_height_fractions': [.0015, .003],
    'minimum_quad_edge_height_fraction': .00002,
    'minimum_native_fan_altitude_height_fraction': .00001,
    'native_fan_projection_safety': 'All four source native-fan signed areas projected onto the summed source-quad normal are strictly positive.',
    'existing_fan_pair_normal_spread_gain_degrees': [3., 12.],
    'aspect_gate': False, 'world_axis_direction_gate': False,
    'weight_equation': 'weight=height_support*geometric_safety*max_edge_fade*existing_warpage_gain',
    'interpolation': 'C2 quintic smoothstep for all nonbinary gains',
    'mask_dtype': 'float32',
    'symmetry': 'Copy the actual source X/Y face-orbit minimum-ID representative to every paired face.',
    'intent': 'Broadly retain existing small nonplanar fan cells, including nearly isotropic and near-horizontal/vertical source quads carrying the user-preferred visible comb. No new geometric pattern is generated by measurement.',
    'shading_scope': 'fine_quads means nonzero geometric accent support only. This measurement does not choose smooth/flat polygon shading.',
}
METRICS = ('max_edge_H', 'min_edge_H', 'min_fan_altitude_H',
           'min_fan_projected_signed_area_H2', 'fan_pair_normal_spread_degrees')
QUANTILES = [0., .01, .1, .5, .9, .99, 1.]


def sha(path):
    h = hashlib.sha256()
    with Path(path).open('rb') as stream:
        for block in iter(lambda: stream.read(8*1024*1024), b''):
            h.update(block)
    return h.hexdigest()


if sha(FROZEN) != FROZEN_SHA:
    raise ValueError('Frozen read-only native-fan measurement helper changed.')
spec = importlib.util.spec_from_file_location('comb_frozen_native_fan_measurement', FROZEN)
frozen = importlib.util.module_from_spec(spec)
spec.loader.exec_module(frozen)
HEIGHT = frozen.HEIGHT


def ah(array):
    return hashlib.sha256(memoryview(np.ascontiguousarray(array)).cast('B')).hexdigest()


def summarize(values):
    return {key: dict(quantiles=QUANTILES, values=np.quantile(values[key], QUANTILES).tolist(),
                      samples=len(values[key])) for key in METRICS}


def counts(weights, safe, subset=None):
    w = weights if subset is None else weights[subset]
    s = safe if subset is None else safe[subset]
    return dict(quads=len(w), geometric_safety_pass=int(s.sum()),
        nonzero_weight_quads=int(np.count_nonzero(w)),
        nonzero_weight_fraction=float(np.count_nonzero(w)/len(w)) if len(w) else 0.,
        weight_ge_point35_quads=int(np.count_nonzero(w >= .35)),
        weight_ge_point35_fraction=float(np.mean(w >= .35)) if len(w) else 0.,
        weight_ge_point95_quads=int(np.count_nonzero(w >= .95)),
        mean_weight=float(w.mean()) if len(w) else 0.,
        maximum_weight=float(w.max()) if len(w) else 0.)


def measure(root):
    started = time.perf_counter()
    if (root/'MASK.npz').exists() or (root/'MEASUREMENT.json').exists():
        raise FileExistsError('Saved single-recipe measurement is immutable.')
    if sha(frozen.SOURCE) != frozen.SOURCE_SHA:
        raise ValueError('Exact revised visual-study source control changed.')
    candidate_path = frozen.SOURCE_ROOT/'RECEIPT.json'
    candidate = frozen.read(candidate_path)
    variant = candidate['variants']['REVISED']
    if variant['control_sha256'] != frozen.SOURCE_SHA:
        raise ValueError('Candidate control source binding differs.')
    render_path = frozen.SOURCE_ROOT/'REVISED_FLAT/views/receipt.json'
    render = frozen.read(render_path)
    camera = render['actual_views']['macro']
    position, target = np.asarray(camera['position']), np.asarray(camera['target'])
    forward = target-position; forward /= np.linalg.norm(forward)
    right = np.cross(forward, [0., 0., 1.]); right /= np.linalg.norm(right)
    up = np.cross(right, forward)
    scale = float(camera['scale'])
    snapshots = {}
    for source in (Path(__file__).resolve(), FROZEN):
        target_snapshot = root/'source_snapshot'/source.parent.name/source.name
        if target_snapshot.exists():
            raise FileExistsError('Source snapshot already exists; preserve prior attempt.')
        target_snapshot.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(source, target_snapshot)
        snapshots[source.parent.name+'/'+source.name] = dict(source=str(source), snapshot=str(target_snapshot), sha256=sha(source))
    with np.load(frozen.SOURCE, allow_pickle=False) as data:
        xyz, faces, chart = data['xyz'], data['faces'], data['chart']
    if xyz.shape != (7002114, 3) or faces.shape != (7002112, 4) or chart.shape != xyz.shape:
        raise ValueError('Actual source G7 control dimensions differ.')
    zmin, zmax = float(xyz[:, 2].min()), float(xyz[:, 2].max())
    actual_height = zmax-zmin
    weights = np.zeros(len(faces), np.float32)
    safe_all = np.zeros(len(faces), bool)
    global_samples = {key: [] for key in METRICS}
    macro_samples = {key: [] for key in METRICS}
    macro_ids, macro_pixels, macro_xy, macro_depth = [], [], [], []
    for start in range(0, len(faces), 65536):
        ids = np.arange(start, min(start+65536, len(faces)))
        q = xyz[faces[ids]]
        metric, safe, centres, normals, _, _, _ = frozen.chunk_metrics(q, chart[faces[ids]])
        z = (centres[:, 2]-zmin)/actual_height
        zlo, zhi = RECIPE['normalized_height_support']
        body = frozen.smoothstep((z-zlo)/RECIPE['height_feather'])*frozen.smoothstep((zhi-z)/RECIPE['height_feather'])
        elo, ehi = RECIPE['maximum_edge_fade_height_fractions']
        edge = frozen.smoothstep((ehi-metric['max_edge_H'])/(ehi-elo))
        wlo, whi = RECIPE['existing_fan_pair_normal_spread_gain_degrees']
        warpage = frozen.smoothstep((metric['fan_pair_normal_spread_degrees']-wlo)/(whi-wlo))
        weights[ids] = (body*safe*edge*warpage).astype(np.float32)
        safe_all[ids] = safe
        representative = (ids % 32) == 0
        for key in METRICS:
            global_samples[key].append(metric[key][representative])
        relative = centres-target
        u, v = relative@right, relative@up
        in_macro = (abs(u) <= scale*.5) & (abs(v) <= scale*.5) & (normals@(-forward) > .05)
        mi = np.flatnonzero(in_macro)
        macro_ids.append(ids[mi])
        projected_xy = np.column_stack([450+u[mi]*900/scale, 450-v[mi]*900/scale])
        macro_xy.append(projected_xy)
        macro_pixels.append(np.clip(projected_xy.astype(np.int32), 0, 899))
        macro_depth.append((centres[mi]-position)@forward)
        for key in METRICS:
            macro_samples[key].append(metric[key][mi])
    px, py, pair_binding = frozen.face_pairs()
    ids = np.arange(len(faces))
    if px.shape != ids.shape or py.shape != ids.shape or not np.array_equal(px[px], ids) or not np.array_equal(py[py], ids) or not np.array_equal(px[py], py[px]):
        raise ValueError('Actual face correspondences are not commuting involutions.')
    source_orbit = np.minimum(np.minimum(ids, px), np.minimum(py, px[py]))
    max_raw_difference = float(np.maximum(abs(weights-weights[px]), abs(weights-weights[py])).max())
    weights = weights[source_orbit]
    safe_all = safe_all[source_orbit]
    fine = weights > 0
    if not np.array_equal(weights, weights[px]) or not np.array_equal(weights, weights[py]) or not np.array_equal(fine, fine[px]) or not np.array_equal(fine, fine[py]):
        raise ValueError('Actual final source-orbit mask symmetry is not exact.')
    if not np.isfinite(weights).all() or weights.min() < 0 or weights.max() > 1:
        raise ValueError('Invalid broad comb weights.')
    all_macro_ids, pixels, depth = np.concatenate(macro_ids), np.concatenate(macro_pixels), np.concatenate(macro_depth)
    slot = pixels[:, 1]*900+pixels[:, 0]
    min_depth = np.full(900*900, np.inf)
    np.minimum.at(min_depth, slot, depth)
    visible = depth <= min_depth[slot] + HEIGHT*.001
    visible_macro = all_macro_ids[visible]
    visible_pixels = np.concatenate(macro_xy)[visible]
    x0, y0, x1, y1 = LOST_ROI
    lost = ((visible_pixels[:, 0] >= x0) & (visible_pixels[:, 0] <= x1) &
            (visible_pixels[:, 1] >= y0) & (visible_pixels[:, 1] <= y1))
    lost_ids = visible_macro[lost]
    global_samples = {key: np.concatenate(value) for key, value in global_samples.items()}
    macro_samples = {key: np.concatenate(value)[visible] for key, value in macro_samples.items()}
    lost_samples = {key: value[lost] for key, value in macro_samples.items()}
    target_mask = root/'MASK.npz'
    np.savez_compressed(target_mask, quad_weight=weights, fine_quads=fine)
    if sha(frozen.SOURCE) != frozen.SOURCE_SHA or sha(FROZEN) != FROZEN_SHA:
        raise ValueError('Actual source or frozen metric helper changed.')
    for binding in snapshots.values():
        if sha(binding['source']) != binding['sha256'] or sha(binding['snapshot']) != binding['sha256']:
            raise ValueError('Executed measurement source snapshot changed.')
    result = dict(date='2026-10-14', recipe=RECIPE,
        source_control=str(frozen.SOURCE), source_control_sha256=frozen.SOURCE_SHA,
        source_candidate_receipt=str(candidate_path), source_candidate_receipt_sha256=sha(candidate_path),
        source_native=str(variant['geometry']), source_native_geometry_sha256=variant['geometry_sha256'],
        source_native_faces_sha256=variant['faces_sha256'], source_flat_render_receipt=str(render_path),
        source_flat_render_receipt_sha256=sha(render_path), original_source_face_pairs=pair_binding,
        physical_reference_height=HEIGHT, source_actual_z_bounds=[zmin, zmax], source_actual_height=actual_height,
        height_scope='Physical thresholds use inherited H; body support uses actual finished-source zmin/zspan.',
        native_fan_scope='Four original cyclic control-edge-to-arithmetic-centre triangles per source quad, established by the revised native receipt. Full native geometry is not reloaded by this measurement.',
        global_counts=counts(weights, safe_all), macro_counts=counts(weights, safe_all, visible_macro),
        lost_preferred_strip_counts=counts(weights, safe_all, lost_ids),
        global_metrics=summarize(global_samples), macro_metrics=summarize(macro_samples),
        lost_preferred_strip_metrics=summarize(lost_samples),
        global_quantile_scope='Every32nd actual source quad; representative quantiles. All mask counts use full actual face arrays.',
        macro_camera=camera, macro_definition='Saved900-square macro orthographic box of width .30; source-quad centroid facing>.05 with per-pixel closest-centroid-depth tolerance .001H. Approximate visibility, not ray-traced occlusion.',
        lost_preferred_strip_pixel_ROI=LOST_ROI,
        lost_ROI_scope='The same lower-right source strip identified in the preceding failed selective-shading audit. ROI applies to approximate-visible macro source-centroid pixels.',
        actual_XY_face_mask_symmetry_exact=True, maximum_pretransport_weight_reflection_difference=max_raw_difference,
        mask=dict(path=str(target_mask), sha256=sha(target_mask), quad_weight_sha256=ah(weights),
                  fine_quads_sha256=ah(fine), quad_weight_dtype=str(weights.dtype)),
        source_snapshots=snapshots, source_geometry_changed=False, candidate_geometry_generated=False,
        shading_changed=False, threshold_sweep_performed=False,
        scope='One broader geometric support measurement on REVISED as visual-study input. No adoption of the complete end revision or geometric/visual success claim.',
        seconds=time.perf_counter()-started)
    target = root/'MEASUREMENT.json'
    target.write_text(json.dumps(result, indent=2, ensure_ascii=False, allow_nan=False)+'\n', encoding='utf-8')
    print(json.dumps(dict(saved=str(target), global_counts=result['global_counts'],
                         macro_counts=result['macro_counts'], lost_preferred_strip_counts=result['lost_preferred_strip_counts']), indent=2), flush=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=DEFAULT_ROOT)
    root = parser.parse_args().root.resolve()
    root.mkdir(parents=True, exist_ok=True)
    measure(root)


if __name__ == '__main__':
    main()
